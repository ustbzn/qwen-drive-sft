#!/usr/bin/env python3
"""Generate a NAVSIM train/val/test log-split YAML for Mogo data.

WHY: the hidden-state / metric caches are built once over the combined
`trainval/` split (the caching entrypoints do not split train vs val). The
train/val separation happens at TRAINING time via `train_logs` / `val_logs`
(lists of log names).

Mogo convention (verified): one pkl == one log, and the pkl filename stem
equals the pkl's internal `log_name` field, which equals the cache
sub-directory name. So the log names are exactly the pkl stems under the
`navsim_logs/` split directories.

Important: Mogo's on-disk `val/` directory is a held-out test set. It must not
participate in training-time train/validation selection. This script therefore
splits `navsim_logs/train/` into `train_logs` and `val_logs`, and writes
`navsim_logs/val/` as `test_logs` for bookkeeping only. The current training
entrypoint consumes only `train_logs` and `val_logs`.

Output is a Hydra config file (placed in the `log_split/` config group) with the
same shape as `config/training/default_train_val_test_log_split.yaml`:

    train_logs:
      - <log_name>
      ...
    val_logs:
      - <log_name>
      ...
    test_logs:
      - <log_name>
      ...

Default output is the `log_split` config group so it can be injected globally:
`navsim/planning/script/config/training/log_split/mogo.yaml`.

Usage:
    python scripts/cache_dataset/gen_mogo_log_split.py \
        --logs-root /pcpt/pcpt/data/VLA/MOGO/recogdrive_dataset/0312_0319/dataset/navsim_logs

Then train by REPLACING `train_logs=null val_logs=null` with the group override
(verified to populate the top-level train_logs/val_logs):
    ... train_test_split=trainval \
        '+log_split@_global_=mogo' \
        cache_path=<qwen3 hidden-state cache>
"""
from __future__ import annotations

import argparse
import math
import random
from pathlib import Path


def log_names_in(split_dir: Path) -> list[str]:
    if not split_dir.is_dir():
        raise SystemExit(f"Split dir not found: {split_dir}")
    return sorted(p.stem for p in split_dir.glob("*.pkl"))


def split_train_val(log_names: list[str], val_ratio: float, seed: int) -> tuple[list[str], list[str]]:
    if not 0.0 < val_ratio < 1.0:
        raise SystemExit(f"--val-ratio must be in (0, 1), got {val_ratio}")

    if len(log_names) < 2:
        raise SystemExit("Need at least 2 train logs to create train/val split")

    val_count = max(1, math.ceil(len(log_names) * val_ratio))
    val_count = min(val_count, len(log_names) - 1)

    shuffled = list(log_names)
    random.Random(seed).shuffle(shuffled)

    val_logs = sorted(shuffled[:val_count])
    train_logs = sorted(shuffled[val_count:])
    return train_logs, val_logs


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--logs-root", required=True,
                    help="navsim_logs root containing train/ and val/ subdirs")
    ap.add_argument(
        "--out",
        default=str(
            Path(__file__).resolve().parents[2]
            / "navsim/planning/script/config/training/log_split/mogo.yaml"
        ),
        help="output YAML path (default: the log_split/mogo.yaml config group)",
    )
    ap.add_argument("--train-subdir", default="train",
                    help="source split to divide into train_logs and val_logs")
    ap.add_argument("--test-subdir", default="val",
                    help="held-out split written as test_logs only")
    ap.add_argument("--val-ratio", type=float, default=0.1,
                    help="fraction of --train-subdir logs used for val_logs")
    ap.add_argument("--seed", type=int, default=0,
                    help="deterministic seed for splitting --train-subdir")
    args = ap.parse_args()

    root = Path(args.logs_root)
    source_train_logs = log_names_in(root / args.train_subdir)
    test_logs = log_names_in(root / args.test_subdir)
    train_logs, val_logs = split_train_val(source_train_logs, args.val_ratio, args.seed)

    overlap = (set(train_logs) | set(val_logs)) & set(test_logs)
    if overlap:
        print(f"WARNING: {len(overlap)} log(s) appear in BOTH train/val and test, "
              f"e.g. {sorted(overlap)[:3]}")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        f.write("# Auto-generated by gen_mogo_log_split.py. Do not edit by hand.\n")
        f.write(f"# train_logs/val_logs are split from navsim_logs/{args.train_subdir}/")
        f.write(f" with val_ratio={args.val_ratio} seed={args.seed}.\n")
        f.write(f"# test_logs come from held-out navsim_logs/{args.test_subdir}/")
        f.write(" and are not used by training.\n")
        f.write("train_logs:\n")
        for name in train_logs:
            f.write(f"  - {name}\n")
        f.write("\nval_logs:\n")
        for name in val_logs:
            f.write(f"  - {name}\n")
        f.write("\ntest_logs:\n")
        for name in test_logs:
            f.write(f"  - {name}\n")

    print(
        f"train_logs: {len(train_logs)}  val_logs: {len(val_logs)}  "
        f"test_logs: {len(test_logs)}  -> {out}"
    )


if __name__ == "__main__":
    main()
